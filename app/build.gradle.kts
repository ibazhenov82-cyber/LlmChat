// Читаем local.properties, чтобы прокинуть DEEPSEEK_API_KEY и LOCAL_HOST_QWEN3 в BuildConfig.
val localProperties = Properties().apply {
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
        load(FileInputStream(localPropertiesFile))
    }
}

fun localProperty(key: String, default: String = ""): String {
    return (localProperties.getProperty(key) ?: System.getenv(key) ?: default)
}

